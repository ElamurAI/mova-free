//! Markdown: treebank card, paper list, per-language index, global index.

use std::fmt::Write as _;

use crate::readme::Readme;
use crate::refs::{How, Matcher, Src};
use crate::release::{Counts, SPLITS, Treebank};

/// A paper from a treebank's list.
pub struct Found {
    pub src: Src,
    pub idx: usize,
    pub how: How,
    /// the year in the reference differs by 1 from the paper's year
    pub fuzzy_year: bool,
    /// ACL ids of other records with the same title, year and author
    pub alts: Vec<String>,
}

/// A reference without a match: raw line and a note.
pub struct Unfound {
    pub raw: String,
    pub note: String,
}

/// Everything about a treebank for output.
pub struct Card<'a> {
    pub tb: &'a Treebank,
    pub readme: &'a Readme,
    pub lang: String,
    pub lang_code: String,
    pub name: String,
    pub family: String,
    pub has_docs: bool,
    pub found: Vec<Found>,
    pub unfound: Vec<Unfound>,
}

pub fn num(n: u64) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i) % 3 == 0 {
            out.push(' ');
        }
        out.push(c);
    }
    out
}

fn cell(s: &str) -> String {
    let s = s.trim();
    if s.is_empty() { "—".into() } else { s.replace('|', "\\|") }
}

/// `de Marneffe, Marie-Catherine; Guillaume, Bruno` → `Marie-Catherine de Marneffe; Bruno Guillaume`.
pub fn contributors(s: &str) -> String {
    s.split(';')
        .map(str::trim)
        .filter(|x| !x.is_empty())
        .map(|a| match a.split_once(',') {
            Some((last, first)) if !first.contains(',') && !first.trim().is_empty() => format!("{} {}", first.trim(), last.trim()),
            _ => a.to_string(),
        })
        .collect::<Vec<_>>()
        .join("; ")
}

fn quote(text: &str) -> String {
    if text.trim().is_empty() {
        return "_The README has no such section._\n".into();
    }
    text.lines().map(|l| if l.trim().is_empty() { ">".to_string() } else { format!("> {l}") }).collect::<Vec<_>>().join("\n") + "\n"
}

fn yes_no(v: &str) -> String {
    match v.trim().to_lowercase().as_str() {
        "yes" => "yes".into(),
        "no" => "no".into(),
        _ => v.to_string(),
    }
}

impl Card<'_> {
    pub fn ud_url(&self) -> String {
        format!("https://universaldependencies.org/treebanks/{}/index.html", self.tb.code)
    }

    pub fn meta(&self, k: &str) -> &str {
        self.readme.meta(k)
    }

    pub fn readme_md(&self, release: &str) -> String {
        let t = self.tb;
        let mut s = format!("# {}\n\n", t.dir);
        let _ = writeln!(
            s,
            "Treebank card from UD release {release}: metadata and texts come from `{}/{}`; size is counted by streaming the `.conllu` files and checked against the release `stats.xml`. Generated by `tools/treebanks build`; do not edit by hand. Papers: [papers.md](papers.md); seeds: `seeds/`; converter: `convert.md`.\n",
            t.dir, t.readme_name
        );
        let contributing = match self.meta("Contributing").trim() {
            "elsewhere" => "outside the UD repo (elsewhere): fixes go to the source or the converter".to_string(),
            "here" => "in the UD repo (here)".to_string(),
            v => v.to_string(),
        };
        let parallel = match self.meta("Parallel").trim() {
            "no" => "no".to_string(),
            v => v.to_string(),
        };
        s.push_str("| Field | Value |\n|---|---|\n");
        let rows: Vec<(&str, String)> = vec![
            ("UD name", t.dir.clone()),
            ("Language", format!("{} (`{}`)", self.lang, self.lang_code)),
            ("Family", self.family.clone()),
            ("Treebank code", format!("`{}`", t.code)),
            ("UD page", format!("{}{}", self.ud_url(), if self.has_docs { "" } else { " (no page in the 24.09 docs snapshot)" })),
            ("License", self.meta("License").to_string()),
            ("Genres", self.meta("Genre").split_whitespace().collect::<Vec<_>>().join(", ")),
            ("Text in data", yes_no(self.meta("Includes text"))),
            ("Parallel", parallel),
            ("In UD since", self.meta("Data available since").to_string()),
            ("Authors", contributors(self.meta("Contributors"))),
            ("Contact", self.meta("Contact").to_string()),
            ("Development", contributing),
        ];
        for (k, v) in rows {
            let _ = writeln!(s, "| {k} | {} |", cell(&v));
        }
        for extra in ["Documentation status", "Data source", "Paragraphs to web"] {
            if !self.meta(extra).is_empty() {
                let _ = writeln!(s, "| {extra} | {} |", cell(self.meta(extra)));
            }
        }
        s.push_str("\n## Annotation layers\n\n| Layer | Origin |\n|---|---|\n");
        for k in ["Lemmas", "UPOS", "XPOS", "Features", "Relations"] {
            let _ = writeln!(s, "| {k} | {} |", cell(self.meta(k)));
        }
        s.push_str(
            "\nUD scale: _manual native_ — annotated by hand directly in UD; _converted from manual_ — converted from manual annotation in another scheme; _converted with corrections_ — converted and partly corrected by hand; _automatic with corrections_ — automatic, with partial manual corrections; _automatic_ — automatic; _not available_ — the layer is absent.\n",
        );
        s.push_str("\n## Size\n\n| Split | Sentences | Tokens | Words | Multiword tokens | Empty nodes |\n|---|---:|---:|---:|---:|---:|\n");
        let row = |s: &mut String, name: &str, c: &Counts| {
            let _ = writeln!(s, "| {name} | {} | {} | {} | {} | {} |", num(c.sentences), num(c.tokens), num(c.words), num(c.fused), num(c.empty));
        };
        for sp in SPLITS {
            if let Some(c) = t.splits.get(&sp) {
                row(&mut s, sp.name(), c);
            }
        }
        row(&mut s, "**total**", &t.total());
        let missing: Vec<&str> = SPLITS.iter().filter(|x| !t.splits.contains_key(x)).map(|x| x.name()).collect();
        s.push_str("\nTokens are surface tokens (Spanish `vámonos` is one), words are syntactic words (`vamos` + `nos`); multiword tokens are those split into several words; empty nodes are the `N.M` nodes of the enhanced graph.");
        if !missing.is_empty() {
            let _ = write!(s, " Splits {} are absent from the release.", missing.join(", "));
        }
        s.push('\n');
        let _ = write!(s, "\n## Summary\n\n{}\n## Introduction\n\n{}", quote(&self.readme.summary()), quote(&self.readme.introduction()));
        s
    }

    pub fn papers_md(&self, m: &Matcher, _papers_link: &str, release: &str) -> String {
        let t = self.tb;
        let mut s = format!("# Papers: {}\n\n", t.dir);
        let _ = writeln!(
            s,
            "References from the README of UD release {release} (References and Citation sections, bibtex, DOI, ACL Anthology URLs) and from the treebank page in the UD documentation, matched against Mova's library of paper cards and the ACL Anthology. Generated by `tools/treebanks build`; do not edit by hand. Card: [README.md](README.md).\n"
        );
        if self.found.is_empty() && self.unfound.is_empty() {
            s.push_str("The treebank README has no references to papers.\n");
            return s;
        }
        let _ = writeln!(s, "## Papers ({})\n", self.found.len());
        if self.found.is_empty() {
            s.push_str("_No reference was found in either the library or the ACL Anthology._\n");
        }
        let mut found: Vec<&Found> = self.found.iter().collect();
        found.sort_by(|a, b| {
            let (pa, pb) = (m.paper(a.src, a.idx), m.paper(b.src, b.idx));
            (pa.year, &pa.title).cmp(&(pb.year, &pb.title))
        });
        for f in found {
            let p = m.paper(f.src, f.idx);
            let who = match p.authors.len() {
                0 => "—".to_string(),
                1..=5 => p.authors.join(", "),
                n => format!("{} et al. ({n})", p.authors[..3].join(", ")),
            };
            let year = if p.year == 0 { "—".to_string() } else { p.year.to_string() };
            let _ = write!(s, "- {year} · {who} · **{}**", p.title.trim());
            match f.src {
                // the paper cards themselves are not in this repository: only the ACL Anthology is linked
                Src::Lib | Src::Acl => {
                    if !p.anthology.is_empty() {
                        let _ = write!(s, " · ACL [`{0}`](https://aclanthology.org/{0}/)", p.anthology);
                    }
                }
            }
            let _ = write!(s, " · {}{}", f.how.label(), if f.fuzzy_year { ", README year ±1" } else { "" });
            if !f.alts.is_empty() {
                let _ = write!(s, " (same record: {})", f.alts.iter().map(|a| format!("`{a}`")).collect::<Vec<_>>().join(", "));
            }
            s.push('\n');
        }
        if !self.unfound.is_empty() {
            let _ = writeln!(s, "\n## Outside the ACL Anthology — not downloaded ({})\n", self.unfound.len());
            s.push_str("Raw reference lines with no match in either the library or the ACL Anthology (matching is strict: a different year or an incomplete title also lands here).\n\n");
            for u in &self.unfound {
                let _ = writeln!(s, "- {}", u.raw);
                if !u.note.is_empty() {
                    let _ = writeln!(s, "  - _{}_", u.note);
                }
            }
        }
        s
    }
}

/// Per-language index: treebanks with size, license, genres, papers.
pub fn lang_md(cards: &[&Card], release: &str) -> String {
    let c0 = cards[0];
    let mut total = Counts::default();
    for c in cards {
        total.add(&c.tb.total());
    }
    let mut s = format!("# {} (`{}`) — UD {release} treebanks\n\n", c0.lang, c0.lang_code);
    let _ = writeln!(
        s,
        "Family: {}. Treebanks: {}; total sentences {}, tokens {}, words {}. Generated by `tools/treebanks build`; all languages: [INDEX.md](../INDEX.md).\n",
        cell(&c0.family),
        cards.len(),
        num(total.sentences),
        num(total.tokens),
        num(total.words)
    );
    s.push_str("| Treebank | UD name | Sentences | Tokens | License | Genres | Papers |\n|---|---|---:|---:|---|---|---:|\n");
    for c in cards {
        let t = c.tb.total();
        let _ = writeln!(
            s,
            "| [{0}]({0}/README.md) | {1} | {2} | {3} | {4} | {5} | [{6}]({0}/papers.md) |",
            c.name,
            c.tb.dir,
            num(t.sentences),
            num(t.tokens),
            cell(c.meta("License")),
            cell(&c.meta("Genre").split_whitespace().collect::<Vec<_>>().join(", ")),
            c.found.len()
        );
    }
    s
}

/// Global index.
pub fn index_md(cards: &[Card], release: &str, archive: &str, stats: &str) -> String {
    let mut total = Counts::default();
    for c in cards {
        total.add(&c.tb.total());
    }
    let langs: std::collections::BTreeSet<&str> = cards.iter().map(|c| c.lang_code.as_str()).collect();
    let mut s = format!("# UD {release} treebanks — index\n\n");
    let _ = writeln!(
        s,
        "Treebanks {}, languages (codes) {}; sentences {}, tokens {}, words {}. {stats}\n\nGenerated by `tools/treebanks build` from `{archive}`; size checked against each treebank's `stats.xml`. Folder layout and purpose: [README.md](README.md).\n",
        cards.len(),
        langs.len(),
        num(total.sentences),
        num(total.tokens),
        num(total.words)
    );
    let mut lic: std::collections::BTreeMap<String, usize> = std::collections::BTreeMap::new();
    for c in cards {
        *lic.entry(cell(c.meta("License"))).or_default() += 1;
    }
    let mut lic: Vec<(String, usize)> = lic.into_iter().collect();
    lic.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    s.push_str("## Licenses\n\n| License | Treebanks |\n|---|---:|\n");
    for (l, n) in lic {
        let _ = writeln!(s, "| {l} | {n} |");
    }
    s.push_str("\n## Languages and treebanks\n\n| Language | Code | Treebank | Sentences | Tokens | License | Papers |\n|---|---|---|---:|---:|---|---:|\n");
    let mut order: Vec<&Card> = cards.iter().collect();
    order.sort_by(|a, b| (a.lang.as_str(), a.name.as_str()).cmp(&(b.lang.as_str(), b.name.as_str())));
    for c in order {
        let t = c.tb.total();
        let _ = writeln!(
            s,
            "| {} | [{1}]({1}/README.md) | [{2}]({1}/{2}/README.md) | {3} | {4} | {5} | [{6}]({1}/{2}/papers.md) |",
            c.lang,
            c.lang_code,
            c.name,
            num(t.sentences),
            num(t.tokens),
            cell(c.meta("License")),
            c.found.len()
        );
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn formatting() {
        assert_eq!(num(1234567), "1 234 567");
        assert_eq!(num(999), "999");
        assert_eq!(contributors("de Marneffe, Marie-Catherine; Guillaume, Bruno; Zeman, Daniel"), "Marie-Catherine de Marneffe; Bruno Guillaume; Daniel Zeman");
        assert_eq!(contributors("Team X"), "Team X");
        assert_eq!(cell("a | b"), "a \\| b");
        assert_eq!(cell("  "), "—");
        assert_eq!(quote("a\n\nb"), "> a\n>\n> b\n");
    }
}
