//! Build script (not to be confused with `src/build.rs` — building the graph from OEWN): compiles the world-model core v3
//! `data/core.tsv` + `data/core-props.tsv` → `$OUT_DIR/core_gen.rs` — enum `CoreId` and static `CORE` records.
//!
//! **Completeness gate:** every core concept has every field — a value, "none", "unknown" with a reason, or "n/a". A missing
//! cell, an unknown field or status, mixed statuses in a cell, two numbers in one field, a row for a concept outside
//! the core, different synsets for one concept — the build fails naming the concept and field. Without `core-props.tsv`
//! the build fails; the first build (to run `onto core-select`) uses `ONTO_CORE_BOOTSTRAP=1`: an empty core.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::Path;

#[path = "src/coregate.rs"]
mod coregate;
use coregate::{DOMAINS, FIELDS, NUMBER};
const ACTS: [(&str, &str); 4] = [("touch", "Touch"), ("approach", "Approach"), ("eat", "Eat"), ("use", "Use")];
const HARMS: [&str; 13] = ["bite", "scratch", "sting", "venom", "kick", "crush", "cut", "burn", "poison", "shock", "allergy", "fall", "drown"];

fn camel(s: &str) -> String {
    s.split(['_', ' ', '-']).filter(|w| !w.is_empty()).map(|w| {
        let mut c = w.chars();
        c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
    }).collect()
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn fnum(s: &str, what: &str) -> String {
    let x: f64 = s.parse().unwrap_or_else(|_| panic!("core: not a number \"{s}\" ({what})"));
    format!("{x:?}")
}

fn main() {
    println!("cargo:rerun-if-changed=data/core.tsv");
    println!("cargo:rerun-if-changed=data/core-props.tsv");
    println!("cargo:rerun-if-changed=src/coregate.rs");
    println!("cargo:rerun-if-env-changed=ONTO_CORE_BOOTSTRAP");
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("core_gen.rs");
    let core_txt = std::fs::read_to_string("data/core.tsv").expect("data/core.tsv");
    let props_path = Path::new("data/core-props.tsv");
    let bootstrap = std::env::var("ONTO_CORE_BOOTSTRAP").as_deref() == Ok("1");
    if !props_path.exists() {
        assert!(bootstrap, "core gate: data/core-props.tsv is missing — run `onto core-select` (first build with ONTO_CORE_BOOTSTRAP=1)");
        std::fs::write(&out, "pub const N_CORE: usize = 0;\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, PartialOrd, Ord)]\npub enum CoreId {}\nimpl CoreId { pub const ALL: [CoreId; 0] = []; }\npub static CORE: [CoreRec; 0] = [];\n").unwrap();
        return;
    }
    let text = std::fs::read_to_string(props_path).unwrap();
    // completeness gate (shared with `onto controls`) — an error stops the build
    let coregate::Parsed { core, cells, synset } = coregate::parse(&core_txt, &text).unwrap_or_else(|e| panic!("{e}"));
    // variant names: a duplicate lemma gets its domain appended
    let mut count: HashMap<&str, usize> = HashMap::new();
    for (l, _) in &core {
        *count.entry(l.as_str()).or_default() += 1;
    }
    let names: Vec<String> = core.iter().map(|(l, d)| if count[l.as_str()] > 1 { format!("{}{}", camel(l), camel(d)) } else { camel(l) }).collect();
    let syn_to_core: HashMap<String, usize> = core.iter().enumerate().filter_map(|(i, k)| synset.get(k).map(|s| (s.clone(), i))).collect();
    let mut s = String::from("// Generated by build.rs from data/core.tsv and data/core-props.tsv — do not edit.\n");
    let _ = writeln!(s, "pub const N_CORE: usize = {};", core.len());
    s.push_str("#[repr(u16)]\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, PartialOrd, Ord)]\npub enum CoreId {\n");
    for n in &names {
        let _ = writeln!(s, "    {n},");
    }
    s.push_str("}\nimpl CoreId {\n");
    let _ = writeln!(s, "    pub const ALL: [CoreId; {}] = [{}];", core.len(), names.iter().map(|n| format!("CoreId::{n}")).collect::<Vec<_>>().join(", "));
    s.push_str("}\n");
    let src = |f: &[String], confirm: &str, note: &str| -> String {
        let conf = if f[11].is_empty() { "0.0".to_string() } else { fnum(&f[11], "conf") };
        let rank = match f[9].as_str() {
            "preferred" => "Rank::Preferred",
            "normal" => "Rank::Normal",
            "deprecated" => "Rank::Deprecated",
            _ => "Rank::None",
        };
        let confirm = match confirm {
            "vmm-yes" => "Confirm::VmmYes",
            "vmm-refine" => "Confirm::VmmRefine",
            "confident" => "Confirm::Confident",
            "vmm-estimate" => "Confirm::VmmEstimate",
            other => panic!("core: unknown confirmation \"{other}\" in \"{}\" {}", f[0], f[3]),
        };
        format!(
            "Source {{ q: {}, p: {}, rank: {rank}, steps: {}, conf: {conf}, confirm: {confirm}, note: {} }}",
            f[7].parse::<u32>().unwrap_or(0),
            f[8].parse::<u16>().unwrap_or(0),
            f[10].parse::<u8>().unwrap_or(0),
            lit(note)
        )
    };
    s.push_str("pub static CORE: [CoreRec; N_CORE] = [\n");
    for (i, k) in core.iter().enumerate() {
        let Some(fields) = cells.get(k) else { panic!("completeness gate: concept \"{} ({})\" has no fields in core-props.tsv", k.0, k.1) };
        let dom = DOMAINS.iter().find(|d| d.0 == k.1).unwrap().1;
        let _ = write!(s, "    CoreRec {{ id: CoreId::{}, lemma: {}, domain: Domain::{dom}, synset: {}", names[i], lit(&k.0.replace('_', " ")), lit(&synset[k]));
        for field in FIELDS {
            let Some(rows) = fields.get(field) else { panic!("completeness gate: concept \"{} ({})\" lacks field {field} — neither values nor an explicit \"unknown\"", k.0, k.1) };
            let st = &rows[0][4];
            assert!(rows.iter().all(|r| &r[4] == st), "core: mixed statuses in cell \"{} ({})\" × {field}", k.0, k.1);
            let rust_field = if field == "use" { "uses" } else if field == "part" { "parts" } else if field == "risk" { "risks" } else { field };
            let v = match st.as_str() {
                "n/a" => "Field::NotApplicable".to_string(),
                "unknown" => format!("Field::Unknown({})", lit(&rows[0][19])),
                "none" => {
                    assert!(field == "risk", "core: \"none\" is only for risks (\"{}\" × {field})", k.0);
                    "Field::Known(&[])".to_string()
                }
                _ if NUMBER.contains(&field) => {
                    assert!(rows.len() == 1, "core: two numbers in field \"{} ({})\" × {field}", k.0, k.1);
                    let r = &rows[0];
                    let sd = if r[14].is_empty() { "None".to_string() } else { format!("Some({})", fnum(&r[14], "sd")) };
                    format!(
                        "Field::Known(Dist {{ mean: {}, sd: {sd}, min: {}, max: {}, n: {}, unit: {}, src: {} }})",
                        fnum(&r[13], "mean"),
                        fnum(&r[15], "min"),
                        fnum(&r[16], "max"),
                        r[17].parse::<u32>().unwrap_or(0),
                        lit(&r[18]),
                        src(r, &r[12], &r[19])
                    )
                }
                _ if field == "risk" => {
                    let mut v = Vec::new();
                    for r in rows {
                        let (a, h) = r[5].split_once(' ').unwrap_or_else(|| panic!("core: risk \"{}\" without action and harm", r[5]));
                        let act = ACTS.iter().find(|x| x.0 == a).unwrap_or_else(|| panic!("core: unknown action \"{a}\"")).1;
                        assert!(HARMS.contains(&h), "core: unknown harm \"{h}\"");
                        v.push(format!("Risk {{ act: Act::{act}, harm: Harm::{}, p: {}, src: {} }}", camel(h), fnum(&r[13], "p"), src(r, &r[12], &r[19])));
                    }
                    format!("Field::Known(&[{}])", v.join(", "))
                }
                _ => {
                    let mut v = Vec::new();
                    for r in rows {
                        let (q, label) = r[5].split_once(' ').unwrap_or((&r[5], ""));
                        let q: u32 = q.trim_start_matches('Q').parse().unwrap_or(0);
                        let core_ref = syn_to_core.get(&r[6]).map(|&j| format!("Some(CoreId::{})", names[j])).unwrap_or_else(|| "None".into());
                        v.push(format!("Val {{ q: {q}, label: {}, synset: {}, core: {core_ref}, src: {} }}", lit(label), lit(&r[6]), src(r, &r[12], &r[19])));
                    }
                    format!("Field::Known(&[{}])", v.join(", "))
                }
            };
            let _ = write!(s, ", {rust_field}: {v}");
        }
        s.push_str(" },\n");
    }
    s.push_str("];\n");
    std::fs::write(&out, s).unwrap();
}
